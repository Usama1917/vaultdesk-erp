export function createI18n(language = "en") {
	let active = normalizeLanguage(language);
	return {
		get language() {
			return active;
		},
		get dir() {
			return active === "ar" ? "rtl" : "ltr";
		},
		setLanguage(nextLanguage) {
			active = normalizeLanguage(nextLanguage);
		},
		t(key, values = {}) {
			const text = (active === "ar" ? ar : en)[key] || en[key] || key;
			return Object.entries(values).reduce(
				(result, [name, value]) => result.replaceAll(`{${name}}`, String(value)),
				text
			);
		},
	};
}

export function detectInitialLanguage(mode) {
	const parameter = new URLSearchParams(window.location.search).get("lang");
	if (mode !== "live" && parameter) return normalizeLanguage(parameter);
	if (mode !== "live") return normalizeLanguage(window.localStorage.getItem("vaultdesk-language") || "en");
	const frappeLanguage = window.frappe?.boot?.lang
		|| window.frappe?.boot?.user?.language
		|| window.frappe?.lang
		|| "en";
	return normalizeLanguage(frappeLanguage);
}

function normalizeLanguage(value) {
	return String(value || "").toLowerCase().startsWith("ar") ? "ar" : "en";
}
